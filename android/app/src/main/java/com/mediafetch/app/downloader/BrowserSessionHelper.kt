package com.mediafetch.app.downloader

import android.net.Uri
import android.webkit.CookieManager
import android.webkit.WebStorage
import java.io.File

object BrowserSessionHelper {
    private const val NETSCAPE_HEADER = "# Netscape HTTP Cookie File\n# Generated by MediaFetch\n\n"
    private const val FUTURE_EXPIRY = "2147483647"
    private val MULTI_TENANT_SUFFIXES = setOf(
        "cloudfront.net",
        "amazonaws.com",
        "github.io",
        "herokuapp.com",
        "netlify.app",
        "vercel.app",
        "pages.dev",
        "blogspot.com",
        "wixsite.com",
    )

    fun ensureCookiesEnabled() {
        try {
            val cm = CookieManager.getInstance()
            cm.setAcceptCookie(true)
        } catch (_: Throwable) {
        }
    }

    fun getCookieCountForUrl(url: String): Int {
        return try {
            val cm = CookieManager.getInstance()
            cm.flush()
            val candidateUrls = expandCandidateUrls(listOf(url))
            val names = HashSet<String>()
            for (candidate in candidateUrls) {
                val raw = cm.getCookie(candidate) ?: continue
                for (pair in raw.split(";")) {
                    val name = pair.substringBefore("=").trim()
                    if (name.isNotEmpty()) {
                        names.add(name)
                    }
                }
            }
            names.size
        } catch (_: Throwable) {
            0
        }
    }

    fun clearSession(onComplete: (() -> Unit)? = null) {
        try {
            val cm = CookieManager.getInstance()
            cm.removeAllCookies {
                cm.flush()
                try {
                    WebStorage.getInstance().deleteAllData()
                } catch (_: Throwable) {
                }
                onComplete?.invoke()
            }
        } catch (_: Throwable) {
            onComplete?.invoke()
        }
    }

    fun exportCookiesToNetscapeFile(targetDir: File, urls: List<String>): File? {
        return try {
            val cm = CookieManager.getInstance()
            cm.flush()

            val candidateUrls = expandCandidateUrls(urls)
            val uniqueCookies = LinkedHashMap<Pair<String, String>, String>()

            for (candidate in candidateUrls) {
                val host = runCatching { Uri.parse(candidate).host }.getOrNull()?.lowercase() ?: continue
                val rawCookieHeader = cm.getCookie(candidate) ?: continue
                val rootDomain = extractRootDomain(host)

                val pairs = rawCookieHeader.split(";")
                for (pair in pairs) {
                    val eqIndex = pair.indexOf('=')
                    if (eqIndex <= 0) continue
                    val name = pair.substring(0, eqIndex).trim()
                    val value = pair.substring(eqIndex + 1).trim()
                    if (name.isEmpty()) continue
                    if (name.contains("\n") || name.contains("\r") || value.contains("\n") || value.contains("\r")) {
                        continue
                    }

                    // Write domain-wide cookie so subdomains (m., www., api., studio.) also match,
                    // while scoping multi-tenant CDN suffixes to the exact host.
                    val domainField = if (rootDomain !in MULTI_TENANT_SUFFIXES && rootDomain.contains('.')) {
                        ".$rootDomain"
                    } else {
                        host
                    }
                    val includeSubdomains = if (domainField.startsWith(".")) "TRUE" else "FALSE"
                    val key = domainField to name
                    uniqueCookies[key] = "$domainField\t$includeSubdomains\t/\tFALSE\t$FUTURE_EXPIRY\t$name\t$value"
                }
            }

            if (uniqueCookies.isEmpty()) {
                return null
            }

            val cookieFile = File(targetDir, "session_cookies.txt")
            cookieFile.writeText(
                buildString {
                    append(NETSCAPE_HEADER)
                    for (line in uniqueCookies.values) {
                        append(line)
                        append('\n')
                    }
                },
                Charsets.UTF_8,
            )
            cookieFile
        } catch (_: Throwable) {
            null
        }
    }

    private fun expandCandidateUrls(urls: List<String>): List<String> {
        val expanded = LinkedHashSet<String>()
        for (raw in urls) {
            val trimmed = raw.trim()
            if (trimmed.isEmpty()) continue
            expanded.add(trimmed)

            val uri = runCatching { Uri.parse(trimmed) }.getOrNull() ?: continue
            val host = uri.host?.lowercase() ?: continue
            val scheme = uri.scheme?.lowercase() ?: "https"
            expanded.add("$scheme://$host/")

            val root = extractRootDomain(host)
            if (root != host) {
                expanded.add("https://$root/")
                expanded.add("https://www.$root/")
            }

            // Google / YouTube share authentication cookies across accounts.google.com and youtube.com
            if (root == "youtube.com" || root == "youtu.be" || root == "google.com") {
                expanded.add("https://www.youtube.com/")
                expanded.add("https://music.youtube.com/")
                expanded.add("https://accounts.google.com/")
                expanded.add("https://www.google.com/")
            }
            if (root == "instagram.com" || root == "facebook.com" || root == "fb.watch") {
                expanded.add("https://www.instagram.com/")
                expanded.add("https://www.facebook.com/")
                expanded.add("https://m.facebook.com/")
            }
            if (root == "x.com" || root == "twitter.com") {
                expanded.add("https://x.com/")
                expanded.add("https://twitter.com/")
            }
        }
        return expanded.toList()
    }

    private fun extractRootDomain(host: String): String {
        val clean = host.removePrefix("www.").removePrefix("m.")
        val parts = clean.split('.').filter { it.isNotBlank() }
        if (parts.size <= 2) {
            return clean
        }
        val lastTwo = "${parts[parts.size - 2]}.${parts[parts.size - 1]}"
        val secondLevelTlds = setOf("co.uk", "com.mx", "com.br", "com.ar", "co.jp", "com.es")
        return if (lastTwo in secondLevelTlds && parts.size >= 3) {
            "${parts[parts.size - 3]}.$lastTwo"
        } else {
            lastTwo
        }
    }
}
